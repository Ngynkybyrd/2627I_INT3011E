"""Verify locked public inputs with production solve_sat, then freeze dataset only."""

import argparse
import importlib.metadata
import json
import sys
from pathlib import Path

import prepare_data as data

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from sudoku.model import load_puzzle
from sudoku.sat import prepare_backend, solve_sat
from sudoku.validation import check_solution


def verify():
    path = ROOT / "data/public-validation.json"
    if path.exists():
        data.finalize_data(ROOT)
        print("Existing evidence rechecked; no repeated solving")
        return
    # Recheck every generated byte before any production verification.
    data.prepare(ROOT, check=True)
    public, _ = data.public_records(ROOT)
    prepare_backend()
    records = []
    for row in public:
        puzzle = load_puzzle(ROOT / row["file"])
        witness_raw = None
        try:
            result = solve_sat(puzzle, "pairwise", cutoff_seconds=10.0)
            result_dict = result.to_dict()
            if result_dict["status"] == "SAT":
                validation = check_solution(puzzle, result.solution)
                if not validation.valid:
                    raise ValueError(f"Independent recheck failed: {validation.message}")
                witness_raw = data.json_bytes({"n": 3, "solution": result_dict["solution"]})
        except Exception as exc:
            result_dict = {"status": "ERROR", "method": "sat", "encoding": "pairwise",
                           "error": f"{type(exc).__name__}: {exc}"}
        checked = {"instance_id": row["instance_id"], "input_sha256": row["sha256"],
                   "result": result_dict, "witness_sha256": None}
        if witness_raw is not None:
            witness_path = ROOT / f"data/witnesses/{row['instance_id']}.json"
            if witness_path.exists() and witness_path.read_bytes() != witness_raw:
                raise ValueError(f"Refusing to overwrite different public witness: {witness_path}")
            if not witness_path.exists():
                with witness_path.open("xb") as stream:
                    stream.write(witness_raw)
            checked["witness_sha256"] = data.sha256(witness_raw)
        records.append(checked)
    evidence = {"purpose": "DATA-007 satisfiability verification, not main benchmark",
                "method": "sat", "encoding": "pairwise", "cutoff_seconds": 10.0,
                "python_version": sys.version.split()[0],
                "python_sat_version": importlib.metadata.version("python-sat"),
                "adapter_sha256_at_verification": data.sha256((ROOT / "src/sudoku/sat.py").read_bytes()),
                "checker_sha256_at_verification": data.sha256((ROOT / "src/sudoku/validation.py").read_bytes()),
                "uniqueness_checked": False, "records": records}
    with path.open("xb") as stream:
        stream.write(data.json_bytes(evidence))
    counts = {}
    for row in records:
        status = row["result"]["status"]
        counts[status] = counts.get(status, 0) + 1
    print("Public production verification status counts: " + json.dumps(counts, sort_keys=True))
    if counts != {"SAT": 20}:
        raise ValueError("Public validation incomplete; evidence saved, no dataset freeze, no reselection")
    data.finalize_data(ROOT)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check existing freeze/evidence only; never solve")
    args = parser.parse_args()
    if args.check:
        if not (ROOT / "data/freeze.json").is_file():
            raise ValueError("Dataset freeze missing")
        data.prepare(ROOT, check=True)
    else:
        verify()
