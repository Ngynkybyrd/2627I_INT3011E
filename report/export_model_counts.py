"""Generate a bilingual structural-count table from accepted diagnostics only."""
from pathlib import Path
import hashlib
import json
import math

report = Path(__file__).resolve().parent
project = report.parent
source = project / 'diagnostics' / 'model' / 'results.json'
evidence = json.loads(source.read_text(encoding='utf-8'))
if evidence.get('result') != 'PASS' or evidence.get('python_sat') != '1.9.dev16':
    raise ValueError('Re-audit the count evidence before updating this table')
rows = evidence['cnf_counts']
expected_order = [(N, e) for N in (4, 9, 16, 25)
                  for e in ('pairwise', 'seqcounter', 'bitwise')]
assert [(r['N'], r['encoding']) for r in rows] == expected_order
lines = [
    '% Generated by export_model_counts.py; do not edit counts by hand.',
    r'\begin{table}[pos=H]', r'\centering',
    r'\caption{\lang{Số đếm cấu trúc từ diagnostics; $C-g$ không gồm clue units.}{Structural counts from diagnostics; $C-g$ excludes clue units.}}',
    r'\label{tab:cnf-counts}', r'\begin{tabular}{rlrrrr}', r'\toprule',
    r'$N$ & AMO & $N^3$ & \lang{Phụ}{Aux.} & $V_e$ & $C_e-g$\\', r'\midrule',
]
for row in rows:
    N, enc, g = row['N'], row['encoding'], row['clues']
    assert row['n'] ** 2 == N and N >= 4 and g == 2
    k = math.ceil(math.log2(N))
    a, c = {'pairwise': (0, N*(N-1)//2),
            'seqcounter': (N-1, 3*N-4), 'bitwise': (k, N*k)}[enc]
    assert row['primary_variables'] == N**3
    assert row['exo_groups'] == 4*N*N
    assert row['auxiliary_variables'] == 4*N*N*a
    assert row['total_variables'] == N**3 + 4*N*N*a
    assert row['clauses'] == 4*N*N*(1+c) + g
    group = next(x for x in evidence['amo_counts']
                 if x['encoding'] == enc and x['length'] == N)
    assert (group['auxiliary_variables'], group['amo_clauses']) == (a, c)
    lines.append(f"{N} & {enc} & {N**3} & {row['auxiliary_variables']} & "
                 f"{row['total_variables']} & {row['clauses']-g}" + r'\\')
lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
(report / 'tables' / 'cnf-counts.tex').write_text('\n'.join(lines), encoding='utf-8')
paths = [source, project/'src'/'sudoku'/'model.py', project/'src'/'sudoku'/'sat.py',
         project/'docs'/'contracts.md']
record = {'status': 'PASS', 'scope': 'structural counts only; no solving or timing',
          'python_sat': evidence['python_sat'], 'checked_rows': len(rows),
          'sources': [{'path': str(p.relative_to(project)),
                       'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
                      for p in paths]}
(report/'logs'/'paper-counts-verification.json').write_text(
    json.dumps(record, indent=2), encoding='utf-8')
print('PASS: 12 structural count rows; group and full-CNF arithmetic agree.')
